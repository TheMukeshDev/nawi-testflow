# ============================================================================
# SETTINGS (gating for Tier 2)
# ============================================================================

class AISettingsUpdate(BaseModel):
    enabled: Optional[bool] = None
    model: Optional[str] = None
    api_key: Optional[str] = None
    clear_key: bool = False


@router.get(
    "/settings",
    summary="AI settings status",
    description="Public AI status (key masked). Any authenticated user.",
)
async def get_settings_status(
    current_user: dict = Depends(require_authenticated),
):
    settings = get_ai_settings()
    data = settings.public_status()
    data["masked_key"] = settings.masked_key()
    return data


@router.put(
    "/settings",
    summary="Admin: update AI settings",
    description=(
        "Admin-only. Change enabled flag, Gemini model, or the global API key "
        "(applies to all users unless they supply a personal key). "
        "All other system settings remain editable on the admin Settings page."
    ),
)
async def put_settings_status(
    payload: AISettingsUpdate,
    current_user: dict = Depends(require_admin),
):
    try:
        settings = update_ai_settings(
            enabled=payload.enabled,
            model=payload.model,
            api_key=payload.api_key,
            clear_key=payload.clear_key,
        )
    except ValueError as exc:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(exc))
    data = settings.public_status()
    data["masked_key"] = settings.masked_key()
    return data


@router.delete(
    "/settings/key",
    summary="Admin: clear global API key",
    description="Admin-only. Removes the global Gemini key (disables Tier 2 until re-added).",
)
async def delete_global_key(
    current_user: dict = Depends(require_admin),
):
    settings = update_ai_settings(clear_key=True)
    data = settings.public_status()
    data["masked_key"] = settings.masked_key()
    return data


# ============================================================================
# TIER 2 — GEMINI ENHANCEMENT (on-demand, gated)
# Request model: { ..., "mode": "rule" | "ai", "api_key": "<personal key>" }
# ============================================================================

def _extract_mode_and_key(payload: dict) -> tuple[str, Optional[str]]:
    mode = str(payload.pop("mode", "ai") or "ai").lower()
    key = payload.pop("api_key", None)
    if key is not None:
        key = str(key).strip() or None
    if mode not in ("rule", "ai"):
        mode = "ai"
    return mode, key


@router.post(
    "/explain-result",
    summary="Explain compliance result (rule-first, optional AI)",
    description=(
        "Default mode='rule' returns the deterministic explanation (no AI). "
        "Pass mode='ai' to explicitly request Gemini enhancement (requires key)."
    ),
)
async def explain_compliance_result(
    decision_data: dict,
    current_user: dict = Depends(require_permission("test_reports:read_completed")),
    x_gemini_key: Optional[str] = Header(default=None),
):
    mode, body_key = _extract_mode_and_key(decision_data)
    if mode == "rule":
        explanation = rule_explainer.explain_decision(decision_data)
        return {"explanation": explanation,
                "_meta": _meta("deterministic_compliance_engine", False, "rule-based")}
    svc = _service_for_request(x_gemini_key, body_key)
    if not svc.is_available:
        explanation = rule_explainer.explain_decision(decision_data)
        meta = _meta("deterministic_compliance_engine", False, "rule-based")
        meta["setup_required"] = True
        meta["hint"] = "Add a Gemini API key in Settings to enable 'Enhance with AI'."
        return {"explanation": explanation, "fallback": svc._fallback_response(
            AIAssistanceType.EXPLAIN_RESULT,
            "Gemini is not configured. Showing rule-based explanation.").to_dict(),
            "_meta": meta}
    response = svc.explain_compliance_result(decision_data)
    return {"assistance": response.to_dict(),
            "_meta": _meta("deterministic_compliance_engine",
                           response.source == "gemini", response.source)}


