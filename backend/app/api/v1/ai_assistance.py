@router.post(
    "/explain-validation",
    summary="Explain validation warning (rule-first, optional AI)",
)
async def explain_validation_warning(
    payload: dict,
    current_user: dict = Depends(require_permission("test_data:create")),
    x_gemini_key: Optional[str] = Header(default=None),
):
    mode, body_key = _extract_mode_and_key(payload)
    warning_data = payload.get("warning_data", payload)
    context = payload.get("context")
    svc = _service_for_request(x_gemini_key, body_key)
    # Validation explanations are cheap deterministic templates by default.
    if mode == "rule" or not svc.is_available:
        resp = svc.explain_validation_warning(warning_data, context)
        # Force rule-template path when gated: rebuild via unavailable service
        if not svc.is_available:
            gated = AIAssistanceService(api_key=None)
            resp = gated.explain_validation_warning(warning_data, context)
            meta = _meta("validation_engine", False, "rule-based")
            meta["setup_required"] = True
            return {"assistance": resp.to_dict(), "_meta": meta}
        return {"assistance": resp.to_dict(),
                "_meta": _meta("validation_engine",
                               resp.source == "gemini", resp.source)}
    response = svc.explain_validation_warning(warning_data, context)
    return {"assistance": response.to_dict(),
            "_meta": _meta("validation_engine",
                           response.source == "gemini", response.source)}


@router.post(
    "/extract-metadata",
    summary="AI: Extract instrument metadata (gated)",
    description="Requires API key — extraction suggestions must be verified.",
)
async def extract_metadata(
    payload: dict,
    current_user: dict = Depends(require_permission("instruments:create")),
    x_gemini_key: Optional[str] = Header(default=None),
):
    document_text = payload.get("document_text", "")
    document_type = payload.get("document_type", "unknown")
    body_key = payload.get("api_key")
    svc = _service_for_request(x_gemini_key, body_key)
    if not svc.is_available:
        meta = _meta(None, False, "rule-based")  # type: ignore[arg-type]
        meta["setup_required"] = True
        meta["hint"] = "Add a Gemini API key in Settings to enable extraction."
        metadata = svc.extract_metadata_from_document(document_text, document_type)
        return {"extracted": metadata.to_dict(), "_meta": meta}
    metadata = svc.extract_metadata_from_document(document_text, document_type)
    return {
        "extracted": metadata.to_dict(),
        "_meta": {
            "type": "ai_assistance",
            "authoritative_source": None,
            "ai_used": True,
            "source": "gemini",
            "disclaimer": (
                "All extracted values are suggestions only. "
                "They MUST be verified by qualified personnel before use."
            ),
            "generated_at": datetime.utcnow().isoformat(),
        },
    }


