"""
NAWI TestFlow — AI Assistance API Routes.

Two-tier explanation strategy (cost-aware):

TIER 1 — RULE-BASED (default, always available, zero AI cost):
    POST /ai/explain-rule      explain one compliance decision (why pass/fail)
    POST /ai/summarize-rule    summarize a report from authoritative data
    GET  /ai/process/{code}    how a test works (formula + procedure)
    These NEVER call Gemini and need NO api key.

TIER 2 — GEMINI ENHANCEMENT (on-demand only):
    POST /ai/explain-result, /summarize-report, /explain-validation,
         /generate-summary, /extract-metadata
    Gemini is called ONLY when the caller passes mode="ai" (or legacy
    behaviour) AND an API key is configured (personal per-request key via
    X-Gemini-Key header / api_key field, else admin global key from Settings)
    AND the feature is enabled. Otherwise a rule-based fallback is returned
    with ai_used=false + setup_required=true so the UI can prompt for a key
    instead of silently burning AI calls.

SETTINGS (gating):
    GET /ai/settings   any authenticated user — public status (key masked)
    PUT /ai/settings   admin only — enabled flag, model, global key
    DELETE /ai/settings/key  admin only — clear global key
"""

from datetime import datetime
from typing import Optional
from fastapi import APIRouter, Depends, Header, HTTPException, status
from pydantic import BaseModel

from app.core.security import (
    require_permission,
    require_admin,
    require_authenticated,
)
from engine.ai_assistance import (
    AIAssistanceService,
    AIAssistanceType,
    get_ai_service,
)
from engine import rule_explainer
from engine.ai_settings import get_ai_settings, update_ai_settings

router = APIRouter(prefix="/ai", tags=["ai-assistance"])


AI_DISCLAIMER = (
    "This content was generated by AI assistance. It is NOT an official "
    "compliance determination, regulatory approval, or certification. "
    "The authoritative source for all compliance decisions is the "
    "deterministic calculation engine."
)

RULE_NOTE = (
    "Rule-based explanation from the deterministic compliance engine "
    "(no AI used, no API key needed)."
)


# ============================================================================
# Helpers
# ============================================================================

def _service_for_request(
    x_gemini_key: Optional[str] = None,
    body_key: Optional[str] = None,
) -> AIAssistanceService:
    """Build a request-scoped service: personal key > global key > env."""
    personal = (body_key or "").strip() or (x_gemini_key or "").strip() or None
    settings = get_ai_settings()
    resolved = settings.resolve_key(personal)
    return AIAssistanceService(
        api_key=resolved, model=settings.model, enabled=settings.enabled
    )


def _meta(authoritative_source: str, ai_used: bool, source: str) -> dict:
    return {
        "type": "ai_assistance" if ai_used else "rule_based_explanation",
        "authoritative_source": authoritative_source,
        "ai_used": ai_used,
        "source": source,
        "disclaimer": AI_DISCLAIMER if ai_used else RULE_NOTE,
        "generated_at": datetime.utcnow().isoformat(),
    }


