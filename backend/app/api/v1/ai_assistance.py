"""
NAWI TestFlow — AI Assistance API Routes

Optional AI-powered assistance endpoints.

IMPORTANT: These endpoints provide ASSISTANCE ONLY.
They do NOT determine compliance, calculate values, or override results.
Every response includes a clear disclaimer.

If AI is unavailable, endpoints return graceful fallback responses
and the application continues to function normally.
"""

