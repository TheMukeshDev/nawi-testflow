@router.get(
    "/status",
    summary="AI: Check service status",
    description="Check if AI assistance is available.",
)
async def get_ai_status(
    current_user: dict = Depends(require_permission("reports:read")),
    ai_service: AIAssistanceService = Depends(get_ai_service),
):
    """Check if AI assistance is available."""
    return {
        "available": ai_service.is_available,
        "model": ai_service.model if ai_service.is_available else None,
        "message": (
            "AI assistance is available."
            if ai_service.is_available
            else "AI assistance is not configured. The application "
                 "functions normally without it."
        ),
    }
