# ============================================================================
# AI DISCLAIMER HEADER
# ============================================================================

AI_DISCLAIMER = (
    "This content was generated by AI assistance. It is NOT an official "
    "compliance determination, regulatory approval, or certification. "
    "The authoritative source for all compliance decisions is the "
    "deterministic calculation engine."
)


# ============================================================================
# EXPLAIN COMPLIANCE RESULT
# ============================================================================

@router.post(
    "/explain-result",
    summary="AI: Explain compliance result",
    description=(
        "Generate a natural-language explanation of a compliance decision. "
        "ASSISTANCE ONLY — does not modify or override the decision."
    ),
)
async def explain_compliance_result(
    decision_data: dict,
    current_user: dict = Depends(require_permission("test_reports:read_completed")),
    ai_service: AIAssistanceService = Depends(get_ai_service),
):
    """
    Explain a compliance decision in natural language.

    This is AI assistance only. The compliance decision is authoritative.
    """
    response = ai_service.explain_compliance_result(decision_data)

    return {
        "assistance": response.to_dict(),
        "_meta": {
            "type": "ai_assistance",
            "authoritative_source": "deterministic_compliance_engine",
            "disclaimer": AI_DISCLAIMER,
            "generated_at": datetime.utcnow().isoformat(),
        },
    }


